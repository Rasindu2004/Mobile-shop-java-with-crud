    private void idKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_idKeyPressed
        // TODO add your handling code here:
        String sidStr = id.getText().trim();

if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
    try {
       

        int stid = Integer.parseInt(sidStr);

   
        PreparedStatement pst = JDBC.connectdb().prepareStatement(
            "SELECT * FROM product WHERE pid= ?");
        pst.setInt(1, stid); // Use setInt for an integer parameter

        ResultSet rs = pst.executeQuery();

      
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

       

      
        while (rs.next()) {
            
            String name = rs.getString("pname");
            String brand = rs.getString("brand");
            String price = rs.getString("price");
            String quantity = rs.getString("quantity");
            String version = rs.getString("version");
            String sid = Integer.toString(rs.getInt("pid")); // Convert int to String

            String tbData[] = {sid, name, brand, price, quantity, version};
            model.addRow(tbData);
        }

  
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "An error occurred: " + e.getMessage());
    }}
    }//GEN-LAST:event_idKeyPressed

